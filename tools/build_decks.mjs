const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const W = 32;

function assertW(rows, name) {
  for (let y = 0; y < rows.length; y++) {
    if (rows[y].length !== W) {
      throw new Error(name + " row " + y + " len " + rows[y].length + " → |" + rows[y] + "|");
    }
  }
}

function assertDoorsPassable(rows, name) {
  const h = rows.length;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < W; x++) {
      const ch = rows[y][x];
      if (ch !== "r" && ch !== "g" && ch !== "b") continue;
      let floors = 0;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = x + dx;
        const ny = y + dy;
        if (ny < 0 || nx < 0 || ny >= h || nx >= W) continue;
        if (rows[ny][nx] !== "#") floors++;
      }
      if (floors < 2) {
        throw new Error(name + " door " + ch + " @" + x + "," + y + " dead T-junction");
      }
    }
  }
}

