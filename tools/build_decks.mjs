function solvable(GM, map) {
  const inv = { R: false, G: false, B: false };
  const sx = Math.floor(map.start.x / map.tile);
  const sy = Math.floor(map.start.y / map.tile);
  function flood() {
    const seen = new Set();
    const q = [[sx, sy]];
    seen.add(sx + "," + sy);
    while (q.length) {
      const [x, y] = q.shift();
      for (const k of map.keys) {
        if (k.taken) continue;
        if (Math.floor(k.x / map.tile) === x && Math.floor(k.y / map.tile) === y) {
          k.taken = true;
          inv[k.colour] = true;
        }
      }
      const t = map.tiles[y][x];
      if (t.kind === "door" && inv[t.colour]) t.open = true;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = x + dx;
        const ny = y + dy;
        if (ny < 0 || nx < 0 || ny >= map.rows || nx >= map.cols) continue;
        const nt = map.tiles[ny][nx];
        if (nt.kind === "wall") continue;
        if (nt.kind === "door" && !nt.open && !inv[nt.colour]) continue;
        if (nt.kind === "door" && inv[nt.colour]) nt.open = true;
        const id = nx + "," + ny;
        if (seen.has(id)) continue;
        seen.add(id);
        q.push([nx, ny]);
      }
    }
    return seen;
  }
  let prev = "";
  for (let n = 0; n < 12; n++) {
    const sig = [inv.R, inv.G, inv.B].join(",");
    if (sig === prev) break;
    prev = sig;
    flood();
  }
  const reach = flood();
  if (!GM.allDoorsOpen(map)) return false;
  return map.exits.some((e) => reach.has(e.tx + "," + e.ty));
}

function shapeSig(rows) {
  // Compact wall-mask fingerprint so we can spot clone layouts
  let s = "";
  for (const row of rows) {
    let bits = 0;
    for (let i = 0; i < row.length; i++) if (row[i] === "#") bits = (bits * 2 + 1) >>> 0;
    s += bits.toString(36) + "|";
  }
  return s;
}

for (const d of DECKS) {
  assertW(d.rows, d.name);
  assertDoorsPassable(d.rows, d.name);
}

const sigs = new Map();
for (const d of DECKS) {
  const sig = shapeSig(d.rows);
  if (sigs.has(sig)) throw new Error("duplicate layout: " + d.name + " == " + sigs.get(sig));
  sigs.set(sig, d.name);
}

const header = readFileSync(join(root, "static/js/map.js"), "utf8");
const start = header.indexOf("  var SECTORS = [");
if (start < 0) throw new Error("SECTORS marker missing");
const keepFrom = header.indexOf("\n\n  function spawnKind", start);
if (keepFrom < 0) throw new Error("spawnKind marker missing");

const sectorsLit = DECKS.map((d) => {
  const rows = d.rows.map((r) => "        " + JSON.stringify(r)).join(",\n");
  return "    {\n      name: " + JSON.stringify(d.name) + ",\n      rows: [\n" + rows + "\n      ]\n    }";
}).join(",\n");

const final = header.slice(0, start) + "  var SECTORS = [\n" + sectorsLit + "\n  ];" + header.slice(keepFrom);
writeFileSync(join(root, "static/js/map.js"), final);

const win = {};
new Function("window", readFileSync(join(root, "static/js/map.js"), "utf8"))(win);
const GM = win.GameMap;
if (GM.sectorCount() !== 20) throw new Error("count " + GM.sectorCount());

for (let i = 0; i < 20; i++) {
  const map = GM.cloneSector(i);
  if (!map.ammoCrates.length) throw new Error("no ammo " + map.name);
  if (!(map.lootCrates || []).length) throw new Error("no loot " + map.name);
  if (!(map.healthBooths || []).length) throw new Error("no health booth " + map.name);
  if (!map.exits.length) throw new Error("no exit " + map.name);
  if (!solvable(GM, map)) throw new Error("softlock " + map.name);
  console.log("ok", map.name);
}
console.log("All 20 decks distinct and solvable.");
